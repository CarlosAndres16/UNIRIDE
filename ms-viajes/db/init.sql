CREATE TABLE IF NOT EXISTS viajes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conductor_id INTEGER NOT NULL CHECK (conductor_id > 0),
  vehiculo_id INTEGER NOT NULL CHECK (vehiculo_id > 0),
  origen_descripcion VARCHAR(255) NOT NULL,
  origen_latitud DOUBLE PRECISION NOT NULL CHECK (origen_latitud BETWEEN -90 AND 90),
  origen_longitud DOUBLE PRECISION NOT NULL CHECK (origen_longitud BETWEEN -180 AND 180),
  destino_descripcion VARCHAR(255) NOT NULL,
  destino_latitud DOUBLE PRECISION NOT NULL CHECK (destino_latitud BETWEEN -90 AND 90),
  destino_longitud DOUBLE PRECISION NOT NULL CHECK (destino_longitud BETWEEN -180 AND 180),
  fecha_salida DATE NOT NULL,
  hora_salida TIME NOT NULL,
  capacidad INTEGER NOT NULL CHECK (capacidad BETWEEN 1 AND 8),
  cupos_ocupados INTEGER NOT NULL DEFAULT 0 CHECK (cupos_ocupados >= 0),
  estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVO'
    CHECK (estado IN ('ACTIVO', 'CANCELADO', 'FINALIZADO')),
  version INTEGER NOT NULL DEFAULT 1,
  idempotency_key VARCHAR(100),
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_cupos_menor_o_igual_capacidad CHECK (cupos_ocupados <= capacidad)
);

CREATE INDEX IF NOT EXISTS idx_viajes_conductor ON viajes (conductor_id);
CREATE INDEX IF NOT EXISTS idx_viajes_vehiculo ON viajes (vehiculo_id);
CREATE INDEX IF NOT EXISTS idx_viajes_fecha ON viajes (fecha_salida, hora_salida);
CREATE INDEX IF NOT EXISTS idx_viajes_estado ON viajes (estado);

CREATE UNIQUE INDEX IF NOT EXISTS ux_viajes_idempotencia
  ON viajes (conductor_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;