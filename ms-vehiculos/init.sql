-- Base unirride_vehiculos (sección 12 del contrato). Columnas en snake_case.
CREATE TABLE IF NOT EXISTS vehiculos (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conductor_id        INTEGER      NOT NULL CHECK (conductor_id > 0),
    placa               VARCHAR(10)  NOT NULL UNIQUE,
    marca               VARCHAR(50)  NOT NULL,
    modelo              VARCHAR(50)  NOT NULL,
    color               VARCHAR(30)  NOT NULL,
    tipo                VARCHAR(30)  NOT NULL,
    capacidad           INTEGER      NOT NULL CHECK (capacidad >= 1),
    estado              VARCHAR(10)  NOT NULL DEFAULT 'ACTIVO'
                        CHECK (estado IN ('ACTIVO', 'INACTIVO')),
    fecha_creacion      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_actualizacion TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_placa_no_vacia CHECK (LENGTH(TRIM(placa)) > 0)
);

CREATE INDEX IF NOT EXISTS idx_vehiculos_conductor_id ON vehiculos (conductor_id);
